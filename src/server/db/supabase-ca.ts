export type DatabaseSsl = false | { ca: string; rejectUnauthorized: true };

const localHosts = new Set(["127.0.0.1", "localhost", "::1"]);

/** TLS options for pg and postgres-js: verified against the Supabase root CA unless the host is local. */
export function databaseSsl(url: string): DatabaseSsl {
  const host = new URL(url).hostname.replace(/^\[|\]$/g, "");
  return localHosts.has(host) ? false : { ca: SUPABASE_ROOT_CA_2021, rejectUnauthorized: true };
}
